"""Step 4: gather every number the report needs into report_numbers_v2.md, copied verbatim from the result files.

    python experiments/report_numbers_v2.py
Nothing is recomputed here: each section is cut from a *_results.md file and labelled with it.
"""
import json
import re
from pathlib import Path

OUT = Path(__file__).parent
SECTIONS = [  # (file, heading to copy, title in the report file)
    ("diagnostics_results.md", "## 4. Each component alone", "Diagnostics: each component alone (tuning data)"),
    ("diagnostics_results.md", "## 5. Structural zeros", "Diagnostics: structural zeros (tuning data)"),
    ("diagnostics_results.md", "## 3. Which rules can fire, and how often they fire", "Diagnostics: rules (tuning data)"),
    ("diagnostics_results.md", "## Most likely causes", "Diagnostics: most likely causes"),
    ("v2_tuning_results.md", "## G and GB: one setting for all five datasets", "Tuning: the chosen global settings (tuning data, optimistic)"),
    ("v2_evaluation_results.md", "## Decision rule for the default", "v1 against v2: decision rule"),
    ("v2_evaluation_results.md", "## Headline: v1 against full v2 (3c)", "v1 against v2: headline (reporting data)"),
    ("v2_evaluation_results.md", "## Cumulative ablation (3b)", "Cumulative ablation (reporting data)"),
    ("v2_evaluation_results.md", "## Does per-dataset tuning carry over? (2d)", "Per-dataset against global tuning (reporting data)"),
    ("subthreshold_benchmark_results.md", None, "Sub-threshold benchmark (reporting data)"),
    ("lstm_retest_results.md", None, "LSTM errors in the forest, re-test (reporting data)"),
    ("narration_v2_results.md", None, "Qwen narration v2"),
]


def section(text: str, heading: str | None) -> str:
    if heading is None:  # the whole file, without its title line
        return text.split("\n", 1)[1].strip()
    start = text.index(heading)
    level = len(heading.split(" ")[0])
    rest = text[start + len(heading):]
    stop = re.search(rf"\n#{{1,{level}}} ", rest)
    return (heading + rest[: stop.start()] if stop else heading + rest).strip()


def main() -> None:
    lines = ["# v2: every number for the report", "",
             "Generated by `experiments/report_numbers_v2.py`. Each section below is copied verbatim from the result file named under its title; "
             "nothing here is recomputed or rounded again. Tuning numbers are optimistic by construction; report the reporting-data tables.", ""]
    for name, heading, title in SECTIONS:
        path = OUT / name
        if not path.exists():
            lines += [f"## {title}", "", f"Not available: `{name}` was not produced in this session.", ""]
            continue
        body = section(path.read_text(), heading)
        body = re.sub(r"^(#+) ", lambda m: "#" * (len(m.group(1)) + 1) + " ", body, flags=re.M)  # nest under the title
        lines += [f"## {title}", "", f"Source: `backend/experiments/{name}`", "", body, ""]
    config = OUT / "v2_config.json"
    if config.exists():
        lines += ["## Frozen v2 settings", "", "Source: `backend/experiments/v2_config.json`", "", "```json",
                  json.dumps(json.loads(config.read_text())["full_v2_settings"], indent=1), "```", ""]
    case = OUT / "nspcl_top50_for_review.csv"
    if case.exists():
        rows = case.read_text().count("\n") - 1
        lines += ["## NSPCL case study", "", f"Source: `backend/experiments/nspcl_top50_for_review.csv` ({rows} alerts). "
                  "Reviewer labels are empty on purpose: no result may be claimed from it until two people have labelled it.", ""]
    (OUT / "report_numbers_v2.md").write_text("\n".join(lines) + "\n")
    print("written")


if __name__ == "__main__":
    main()
